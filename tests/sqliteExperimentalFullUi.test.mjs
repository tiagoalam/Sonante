test("successful folder indexing refreshes the visible catalog and always clears loading state", () => {
  const app = read("../src/App.tsx");
  const start = app.indexOf("const addSqliteFolder = useCallback");
  const end = app.indexOf("const verifySqliteSource = useCallback", start);
  assert.notEqual(start, -1);
  assert.notEqual(end, -1);
  const add = app.slice(start, end);
  assert.match(add, /finally\s*\{[\s\S]*setSqliteIndexing\(false\)/);
  assert.match(add, /catch\s*\(error\)[\s\S]*phase: "failed"/);
  assert.match(add, /requestRefresh\(\)/);
  const verifyEnd = app.indexOf("const beginConfigSave", end);
  const verify = app.slice(end, verifyEnd);
  assert.match(verify, /finally\s*\{[\s\S]*setSqliteIndexing\(false\)/);
  assert.match(verify, /catch\s*\(error\)[\s\S]*phase: "failed"/);
});
